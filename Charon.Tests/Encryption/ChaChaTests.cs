internal static class ChaChaTests {
	[Test]
	public static void DecryptTest() {
		var vec = new byte[] {
			0xde, 0xc2, 0x0e, 0xe4, 0xc0, 0x0c, 0xec, 0xf6, 0x97, 0x64, 0xf3, 0xf4, 0x57, 0xbf, 0x14, 0x61,
			0x79, 0xa2, 0x55, 0xde, 0x7b, 0x2c, 0xac, 0x63, 0x50, 0x4b, 0x5b, 0x9d, 0x63, 0x14, 0x99, 0x0d,
			0x29, 0xd6, 0xb1, 0x99, 0x42, 0x0d, 0x23, 0x7d, 0x9d, 0xb6, 0xc6, 0xd4, 0x9c, 0x72, 0x7d, 0xfc,
			0x33, 0x7b, 0x6f, 0x5b, 0x23, 0xaf, 0x6f, 0x3e, 0xf0, 0x3c, 0x10, 0xfb, 0xdb, 0xbf, 0xf6, 0x33,
		};
		var exp = "Neptune/Charon/Neptune/Charon/Neptune/Charon/Neptune/Charon/Nept"u8.ToArray();
		var vecSpan = vec.AsSpan();
		var key = "_CHARON__CHARON__CHARON__CHARON_"u8.ToArray();
		var iv = "NEPTUNE_NEPT"u8.ToArray();
		const uint COUNTER = 1u;
		const int ROUNDS = 20;

		var cha = new ChaChaAlgorithm(key, iv, ChaChaAlgorithm.DefaultState, COUNTER);
		cha.CryptBytes(ref vecSpan, 0, vec.Length);
		Assert.That(vec, Is.EqualTo(exp).AsCollection);
	}

